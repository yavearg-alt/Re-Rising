"""Build the standalone SAOUB Launcher for players: no Python to install, every game file included (maintainers).

usage: .venv/Scripts/python tools/launcher/build_bundle.py [--apk saoub_private.apk] [--no-game] [--no-zip]
   -> <data>/build/launcher_bundle/SAOUB_Launcher/          (the folder, runnable as is)
      <data>/build/launcher_bundle/SAOUB_Launcher_v<N>.zip  (what players download, ~6 GB)

Layout of SAOUB_Launcher/
  SAOUB_Launcher.exe, _internal/   Python 3 + tkinter + msgpack + pycryptodome + the whole standard library
                                   (PyInstaller, entry point tools/launcher/boot.py); the exe also runs the server
  server/, tools/                  the server and launcher code as .py files: what code updates replace
  game/                            the server's data folder (SAOUB_DATA): master caches and data, manifests, every
                                   game file (dump hashed + restored; the APK-only ones are read from the APK
                                   below): the game downloads everything from the local server, no VPS
  downloads/saoub_bluestacks.apk   the game patched for http://10.0.2.2:8080 (API, CDN, GREE), for BlueStacks
  README.txt
iOS-only files (<data>/ios_only) are left out: Android client only.
The whole standard library is bundled so that a later code update can import any stdlib module; a new third-party
library (requirements.txt) needs a new bundle. Game files are hard-linked into the folder (no extra disk space).
PyInstaller runs from its own venv (BUILD_VENV, created on first use), not the project's .venv.
"""
import argparse
import glob
import json
import os
import shutil
import subprocess
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import updater  # noqa: E402

ROOT = updater.ROOT
DATA = os.environ.get("SAOUB_DATA") or os.path.join(ROOT, "data")
BUILD_VENV = DATA + "/tools/launcher_build_venv"
OUT = DATA + "/build/launcher_bundle"
APP = OUT + "/SAOUB_Launcher"
DEFAULT_APK = DATA + "/build/saoub_private.apk"  # tools/build_apk.sh http://10.0.2.2:8080 (CDN on the same server)
UPDATE_OUT = os.environ.get("SAOUB_UPDATE_OUT", DATA + "/build/launcher_update")
CONTENTS = "dump/data/data/com.bandainamcoent.saoars/files/contents"

# game data copied into game/ (relative to DATA; "**" = whole tree)
GAME_FILES = [
    "server_cache/master_*.json", "server_cache/manifest_*_v2.json", "server_cache/manifest_*_v2_r*.json",
    "server_cache/zips_*/index.json", "server_cache/overrides/*",
    "extracted/sample_user/*", "extracted/master_json/*.json", "extracted/master_final/*",
    "extracted/manifest/resolved_paths.json",
    CONTENTS + "/manifest/*", CONTENTS + "/hashed/**", "restored/hashed/**",
]

# never needed by the server or the launcher: keeps the bundle smaller
STDLIB_SKIP = {"test", "idlelib", "turtledemo", "ensurepip", "lib2to3", "pydoc_data", "venv", "tkinter.test",
               "unittest.test", "distutils", "msilib", "antigravity", "this", "__phello__", "_testcapi",
               "_testinternalcapi", "_testbuffer", "_testimportmultiple", "_testmultiphase", "_testsinglephase",
               "_xxtestfuzz", "_xxsubinterpreters", "_xxinterpchannels", "_ctypes_test", "xxlimited", "xxlimited_35"}

SPEC = """# generated by tools/launcher/build_bundle.py
from PyInstaller.utils.hooks import collect_submodules
hidden = {hidden!r} + collect_submodules("msgpack") + collect_submodules(
    "Crypto", filter=lambda name: not name.startswith("Crypto.SelfTest"))
a = Analysis([{boot!r}], hiddenimports=hidden, excludes={excludes!r})
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name="SAOUB_Launcher", console=False, upx=False)
coll = COLLECT(exe, a.binaries, a.datas, name="SAOUB_Launcher", upx=False)
"""

STDLIB_LIST = r"""
import json, pkgutil, sys, importlib.util
skip = set(json.loads(sys.argv[1]))
names = []
for top in sorted(sys.stdlib_module_names):
    if top in skip or importlib.util.find_spec(top) is None:
        continue
    names.append(top)
    spec = importlib.util.find_spec(top)
    if spec.submodule_search_locations:
        for m in pkgutil.walk_packages(spec.submodule_search_locations, top + "."):
            if not any(m.name == s or m.name.startswith(s + ".") for s in skip) and ".test" not in m.name:
                names.append(m.name)
print(json.dumps(names))
"""

README = """SAO Unleash Blading - private server launcher (version {version})

1. Double-click SAOUB_Launcher.exe (Windows may warn about an unknown app: More info > Run anyway).
2. Click START SERVER and wait for ONLINE.
3. CONNECT THE GAME > INSTALL INTO BLUESTACKS (BlueStacks 5 open, Settings > Advanced > Android Debug Bridge on),
   or drag downloads\\saoub_bluestacks.apk onto the BlueStacks window. Uninstall the original game first if needed.
4. Launch the game. Everything runs on this PC: no internet needed once installed.

Your accounts are in server\\saoub.sqlite3: HOME > Back up database saves a copy. UPDATE installs new versions.
Keep this folder private: it contains the game's files.

Re:Rising - open-source SAO Unleash Blading revival server and launcher (see LICENSE in the repository).
Do not share this folder: it contains the game's files.
SAO Unleash Blading and its game files belong to Bandai Namco Entertainment.
"""


def build_python() -> str:
    py = os.path.join(BUILD_VENV, "Scripts", "python.exe")
    if not os.path.exists(py):
        subprocess.run([os.path.join(sys.base_prefix, "python.exe"), "-m", "venv", BUILD_VENV], check=True)
        subprocess.run([py, "-m", "pip", "install", "-q", "pyinstaller", "-r", os.path.join(ROOT, "requirements.txt")],
                       check=True)
    return py


def build_exe():
    py = build_python()
    hidden = json.loads(subprocess.run([py, "-c", STDLIB_LIST, json.dumps(sorted(STDLIB_SKIP))], check=True,
                                       capture_output=True, text=True).stdout)
    work = OUT + "/pyinstaller"
    os.makedirs(work, exist_ok=True)
    spec = os.path.join(work, "SAOUB_Launcher.spec")
    with open(spec, "w", encoding="utf-8") as f:
        f.write(SPEC.format(hidden=hidden, boot=os.path.join(ROOT, "tools", "launcher", "boot.py"),
                            excludes=sorted(STDLIB_SKIP)))
    print(f"PyInstaller: {len(hidden)} stdlib modules", flush=True)
    subprocess.run([py, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
                    "--distpath", OUT, "--workpath", work + "/build", spec], check=True)


def link(src: str, dst: str):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.exists(dst):
        os.remove(dst)
    try:
        os.link(src, dst)  # same volume: no copy, no extra space
    except OSError:
        shutil.copy2(src, dst)


def add_code(version: int):
    for rel in updater.code_files():
        if rel.endswith(".bat") or rel == "requirements.txt":
            continue
        dst = os.path.join(APP, *rel.split("/"))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, *rel.split("/")), dst)
    with open(os.path.join(APP, "tools", "launcher", "version.json"), "w", encoding="utf-8") as f:
        f.write(json.dumps({"version": version}) + "\n")
    with open(os.path.join(APP, "README.txt"), "w", encoding="utf-8", newline="\r\n") as f:
        f.write(README.format(version=version))


def add_game() -> int:
    count = size = 0
    for pattern in GAME_FILES:
        for src in glob.glob(os.path.join(DATA, pattern), recursive=True):
            if os.path.isfile(src) and not src.endswith((".tmp", ".bak")):
                link(src, os.path.join(APP, "game", os.path.relpath(src, DATA)))
                count += 1
                size += os.path.getsize(src)
    print(f"game: {count} files, {size // 1048576} MB", flush=True)
    return count


def make_zip(version: int) -> str:
    out = os.path.join(OUT, f"SAOUB_Launcher_v{version}.zip")
    tmp = out + ".part"
    with zipfile.ZipFile(tmp, "w", allowZip64=True) as z:
        for d, _, files in os.walk(APP):
            for f in files:
                full = os.path.join(d, f)
                rel = os.path.relpath(full, OUT).replace("\\", "/")
                # game files and the APK are already compressed: stored, much faster
                stored = rel.startswith(("SAOUB_Launcher/game/", "SAOUB_Launcher/downloads/"))
                z.write(full, rel, zipfile.ZIP_STORED if stored else zipfile.ZIP_DEFLATED)
    os.replace(tmp, out)
    print(f"{out}: {os.path.getsize(out) // 1048576} MB")
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--apk", default=DEFAULT_APK, help="APK for BlueStacks (http://10.0.2.2:8080); '' = none")
    p.add_argument("--no-game", action="store_true", help="without game/ (players pick a data folder)")
    p.add_argument("--no-zip", action="store_true")
    p.add_argument("--skip-exe", action="store_true", help="reuse the exe of the previous build")
    args = p.parse_args()
    # same code version as the last published update, so a fresh install is not offered that update again
    version = int(updater.load_json(os.path.join(UPDATE_OUT, "update.json"), {}).get("version", 0))
    if not args.skip_exe:
        build_exe()
    # from scratch (game files are hard links: cheap to redo); drops test databases, logs and runtime caches
    for sub in ("server", "tools", "game", "downloads"):
        shutil.rmtree(os.path.join(APP, sub), ignore_errors=True)
    add_code(version)
    if not args.no_game:
        add_game()
    if args.apk:
        link(args.apk, os.path.join(APP, "downloads", "saoub_bluestacks.apk"))
    print(f"bundle v{version} -> {APP}", flush=True)
    if not args.no_zip:
        make_zip(version)


if __name__ == "__main__":
    main()
